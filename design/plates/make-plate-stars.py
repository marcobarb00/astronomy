"""Build design/plates/plate-stars.js from the SIMBAD and Hipparcos data in
tools/numbers/data (fetched by fetch-plate-stars.sh). Run from the
repository root: python3 design/plates/make-plate-stars.py

Every star brighter than V = 5.0 in the regions of the plates, plus the
stars of the constellation figures (some of which have no V in SIMBAD's
"allfluxes" table: their V comes from the "flux" table or, for eta UMi and
gam Cep, from Hipparcos)."""
import csv

DATA = 'tools/numbers/data/'
HIPPARCOS = {'eta UMi': '79822', 'gam Cep': '116727'}


def clean(identifier):
    """'*  17 Tau' -> '17 Tau', '* alf UMa' -> 'alf UMa'."""
    return ' '.join(identifier.lstrip('*').split())


stars = {}

for name in ('plate-stars-2026-10-19.csv', 'plate-figure-stars-2026-10-19.csv'):
    for row in csv.DictReader(open(DATA + name)):
        row['V'] = row.get('V', row.get('v', ''))   # the flux query names it 'v'
        key = clean(row['main_id'])
        if key not in stars or not stars[key]['V']:
            stars[key] = row

hip = {row['HIP']: row['Vmag'] for row in csv.DictReader(open(DATA + 'plate-hipparcos-V-2026-10-19.csv'))}
for key, number in HIPPARCOS.items():
    stars[key]['V'] = hip[number]

lines = []
for key, row in sorted(stars.items(), key=lambda item: float(item[1]['V'])):
    lines.append(f"\t{{ id: '{key}', ra: {row['ra']}, dec: {row['dec']}, "
                 f"pmra: {row['pmra'] or 0}, pmdec: {row['pmdec'] or 0}, mag: {row['V']} }}")

with open('design/plates/plate-stars.js', 'w') as out:
    out.write("/* GENERATED by design/plates/make-plate-stars.py from the SIMBAD and\n"
              "   Hipparcos data in tools/numbers/data: do not edit by hand.\n"
              "   The stars of the plate previews: id (SIMBAD), ra and dec (deg, ICRS\n"
              "   J2000), pmra and pmdec (mas / yr), mag (V). */\n\n"
              "const PLATE_STARS = [\n" + ',\n'.join(lines) + '\n];\n')
print(len(lines), 'stars')
