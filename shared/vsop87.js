/* ==========================================================================
   PREDICTING THE SKY - THE REFERENCE OF PAGE 4.5 AND THE TOOLBOX
   (vsop87.js)
   The planets of the reference sky (ephemeris.js) are Kepler ellipses
   whose elements drift slowly (Standish's Table 2): a Kepler model fitted
   to them would match them almost by construction (STRUCTURE.md, page
   4.5). This file gives the Earth and the planets from VSOP87, a theory
   that adds the planets' pulls on one another to the ellipses, so that
   page 4.5 and the toolbox can judge Kepler's model. It adds itself to Ephem as the theory
   'vsop87', used when Ephem is asked for { theory: 'vsop87' }
   (ephemeris.js, section 7).
   Needs ephemeris.js and vsop87-data.js (the terms of the Earth and
   Mars, generated by tools/make-vsop87.js); vsop87-planets.js, loaded
   between the two by the pages that need them (the toolbox, the
   epilogue), adds Mercury, Venus, Jupiter and Saturn.
   Touches no DOM, so it can be loaded in Node.

   SOURCE
	 P. Bretagnon and G. Francou, "Planetary theories in rectangular and
	 spherical variables. VSOP 87 solutions", A&A 202, 309 (1988): version
	 B, heliocentric ecliptic coordinates L, B, R referred to the J2000
	 ecliptic and equinox, from the IMCCE's files (fetched by
	 tools/numbers/data/fetch-vsop87.sh). Kept: the terms of amplitude
	 1e-7 or more: 220 for the Earth, 606 for Mars, 289 for Mercury, 174
	 for Venus, 790 for Jupiter and 1359 for Saturn.

   ACCURACY (measured, not quoted)
	 Against JPL Horizons (DE441, heliocentric vectors in the J2000
	 ecliptic) every 300 days from 1900 to 2150 (tools/make-vsop87.js):
	 within 0.31" for the Earth and for Mars in heliocentric ecliptic
	 longitude, and within 0.61" for Mars' direction seen from the Earth
	 (the full series: 0.11", 0.12", 0.40"). Seen from the Earth, Mercury
	 within 0.30", Venus 0.62", Jupiter 0.81" and Saturn 0.69" (the full
	 series: 0.12", 0.11", 0.70", 0.47"). The series are valid for some
	 thousands of years; the terms were kept for AD 1000 to 3000.

   TABLE OF CONTENTS
	 1. Evaluating a series
	 2. Export, and the theory added to Ephem
   ========================================================================== */

const Vsop87 = (function () {
	/* ======================================================================
	   1. EVALUATING A SERIES
	   ====================================================================== */

	/* The bodies this file holds. */
	const BODIES = Object.keys(VSOP87_DATA);

	/* The value of one variable (a list of powers of t). */
	function variable(powers, t) {
		let sum = 0;
		let tk = 1;

		powers.forEach(terms => {
			let value = 0;

			terms.forEach(([A, B, C]) => {
				value += A * Math.cos(B + C * t);
			});
			sum += value * tk;
			tk *= t;
		});

		return sum;
	}

	/* Heliocentric rectangular position (au) of a body of BODIES in the
	   J2000 ecliptic frame, at JD (TT, taken as TDB: they differ by under
	   2 ms). */
	function heliocentricJ2000(body, jdTT) {
		const series = VSOP87_DATA[body];

		if (!series) {
			throw new Error(`Vsop87: no series for "${body}"`);
		}

		const t = (jdTT - 2451545.0) / 365250;
		const L = variable(series[0], t);
		const B = variable(series[1], t);
		const R = variable(series[2], t);

		return [R * Math.cos(B) * Math.cos(L), R * Math.cos(B) * Math.sin(L), R * Math.sin(B)];
	}

	/* ======================================================================
	   2. EXPORT
	   ====================================================================== */

	return {
		BODIES,
		heliocentricJ2000
	};
})();

Ephem.addTheory('vsop87', Vsop87.heliocentricJ2000);
